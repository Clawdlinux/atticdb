#!/usr/bin/env bash
# Prints the Homebrew formula for an AtticDB release, from that release's SHA256SUMS.
#
#   scripts/brew-formula.sh 0.4.0 dist/SHA256SUMS > Formula/atticdb.rb
#
# The formula installs the prebuilt release binary, so brew needs no Rust toolchain.

set -euo pipefail

version=${1:?usage: brew-formula.sh <x.y.z> <SHA256SUMS>}
sums=${2:?usage: brew-formula.sh <x.y.z> <SHA256SUMS>}
if ! printf '%s\n' "$version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$'; then
    echo "brew-formula: version must be x.y.z, got $version" >&2
    exit 2
fi

sum() {
    local hash
    hash=$(awk -v name="atticdb-$1.tar.gz" '$2 == name { print $1 }' "$sums")
    if ! printf '%s\n' "$hash" | grep -Eq '^[0-9a-f]{64}$'; then
        echo "brew-formula: no sha256 for atticdb-$1.tar.gz in $sums" >&2
        exit 1
    fi
    echo "$hash"
}

base="https://github.com/Clawdlinux/atticdb/releases/download/v$version"
mac_arm=$(sum aarch64-apple-darwin)
mac_intel=$(sum x86_64-apple-darwin)
linux_arm=$(sum aarch64-unknown-linux-musl)
linux_intel=$(sum x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/brew-formula.sh in Clawdlinux/atticdb. Edits here are overwritten.
class Atticdb < Formula
  desc "Local, durable memory for coding agents"
  homepage "https://atticdb.com"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$base/atticdb-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/atticdb-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/atticdb-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/atticdb-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "atticdb"
  end

  def caveats
    <<~TEXT
      Set up memory and connect your agents:
        atticdb setup
    TEXT
  end

  test do
    assert_equal "atticdb #{version}", shell_output("#{bin}/atticdb --version").strip
  end
end
EOF
